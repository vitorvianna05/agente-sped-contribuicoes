CREATE TABLE rag.operations (
    operation_id uuid PRIMARY KEY,
    type text NOT NULL CHECK (type IN ('ingestion','approve','reprocess','withdraw','expurge')),
    document_version_id uuid NULL,
    generation_id uuid NULL,
    principal_id text NOT NULL CHECK (length(principal_id) > 0),
    correlation_id text NOT NULL CHECK (length(correlation_id) > 0),
    state text NOT NULL CHECK (state IN ('queued','processing','succeeded','failed','cancelled')),
    created_at timestamptz NOT NULL,
    started_at timestamptz NULL,
    finished_at timestamptz NULL,
    lease_until timestamptz NULL,
    lease_owner text NULL,
    attempt_number integer NOT NULL CHECK (attempt_number >= 0),
    result_code text NULL,
    idempotency_key_digest text NOT NULL CHECK (idempotency_key_digest ~ '^[a-f0-9]{64}$'),
    request_digest text NOT NULL CHECK (request_digest ~ '^[a-f0-9]{64}$'),
    UNIQUE (principal_id, type, idempotency_key_digest),
    CHECK ((lease_until IS NULL) = (lease_owner IS NULL)),
    CHECK (state <> 'processing' OR (started_at IS NOT NULL AND lease_until IS NOT NULL)),
    CHECK (state NOT IN ('succeeded','failed','cancelled') OR finished_at IS NOT NULL),
    CHECK (started_at IS NULL OR started_at >= created_at),
    CHECK (finished_at IS NULL OR finished_at >= started_at)
);
